-- واحدها
CREATE TABLE departments (
    department_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    department_name  VARCHAR2(100) NOT NULL,
    CONSTRAINT dept_name_uk UNIQUE (department_name)
);

-- سمت‌های شغلی
CREATE TABLE job_titles (
    job_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    job_title   VARCHAR2(100) NOT NULL,
    min_salary  NUMBER(12,2),
    max_salary  NUMBER(12,2),
    CONSTRAINT job_title_uk UNIQUE (job_title),
    CONSTRAINT job_salary_ck CHECK (max_salary >= min_salary)
);

-- کارمندان
CREATE TABLE employees (
    employee_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    national_cod    VARCHAR2(10)  NOT NULL,
    first_name      VARCHAR2(50)  NOT NULL,
    last_name       VARCHAR2(50)  NOT NULL,
    email           VARCHAR2(150) NOT NULL,
    phone           VARCHAR2(20),
    hire_date       DATE DEFAULT SYSDATE NOT NULL,
    salary          NUMBER(12,2),
    department_id   NUMBER,
    job_id          NUMBER,
    manager_id      NUMBER,
    status          VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT emp_email_uk   UNIQUE (email),
    CONSTRAINT emp_status_ck  CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT emp_dept_fk    FOREIGN KEY (department_id) REFERENCES departments (department_id),
    CONSTRAINT emp_job_fk     FOREIGN KEY (job_id)        REFERENCES job_titles (job_id),
    CONSTRAINT emp_mgr_fk     FOREIGN KEY (manager_id)    REFERENCES employees (employee_id)
);
